const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('fn', {
  platform: process.platform,
  restore: () => ipcRenderer.invoke('auth:restore'),
  serverInfo: (server) => ipcRenderer.invoke('auth:server-info', { server }),
  login: (payload) => ipcRenderer.invoke('auth:login', payload),
  relogin: () => ipcRenderer.invoke('auth:relogin'),
  logout: () => ipcRenderer.invoke('auth:logout'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  chooseWallpaper: () => ipcRenderer.invoke('wallpaper:choose'),
  getWallpaper: () => ipcRenderer.invoke('wallpaper:get'),
  clearWallpaper: () => ipcRenderer.invoke('wallpaper:clear'),
  chooseLyricsBackground: () => ipcRenderer.invoke('lyrics:choose-background'),
  getLyricsBackground: () => ipcRenderer.invoke('lyrics:get-background'),
  clearLyricsBackground: () => ipcRenderer.invoke('lyrics:clear-background'),
  coverCacheStats: () => ipcRenderer.invoke('covers:stats'),
  clearCoverCache: () => ipcRenderer.invoke('covers:clear'),
  getPrefs: () => ipcRenderer.invoke('prefs:get'),
  setPrefs: (p) => ipcRenderer.invoke('prefs:set', p),
  setTheme: (mode) => ipcRenderer.send('theme:set', mode),
  setOverlay: (o) => ipcRenderer.send('overlay:set', o),
  trayInfo: () => ipcRenderer.invoke('tray:info'),
  setPlayerState: (s) => ipcRenderer.send('player:state', s),
  lyricsGet: () => ipcRenderer.invoke('lyrics:get'),
  lyricsSetOn: (on) => ipcRenderer.invoke('lyrics:set-on', !!on),
  lyricsSetStyle: (patch) => ipcRenderer.invoke('lyrics:set-style', patch || {}),
  lyricsResetStyle: () => ipcRenderer.invoke('lyrics:reset-style'),
  lyricsResetPosition: () => ipcRenderer.send('lyrics:reset-position'),
  onLyricsSettings: (cb) => { const h = () => cb(); ipcRenderer.on('lyrics:open-settings', h); return () => ipcRenderer.removeListener('lyrics:open-settings', h) },
  onLyricsOnChanged: (cb) => { const h = (_e, on) => cb(!!on); ipcRenderer.on('lyrics:on-changed', h); return () => ipcRenderer.removeListener('lyrics:on-changed', h) },
  onPlayerCommand: (cb) => { const h = (_e, cmd, arg) => cb(cmd, arg); ipcRenderer.on('player:command', h); return () => ipcRenderer.removeListener('player:command', h) },
  onNav: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on('nav', h); return () => ipcRenderer.removeListener('nav', h) },
  minimize: () => ipcRenderer.send('win:minimize'),
  toggleMaximize: () => ipcRenderer.send('win:toggle-maximize'),
  close: () => ipcRenderer.send('win:close'),
})
